import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { Readable } from 'node:stream';
import express from 'express';
import sharp from 'sharp';
import { ChatService, chatConfig } from './chat.js';
import { SocialService } from './service.js';
import { Store } from './store.js';
import { createSocialRouter } from './routes.js';
import { helperSelftest } from './helper-selftest.js';
import { chatOperation } from './chat-routes.js';

const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'esteria-chat-'));
let store = new Store(directory);
await store.load();
let social = new SocialService(store);
const config = chatConfig({ CHAT_BRIDGE_SECRET: 'x'.repeat(32) });
let chat = social.chat = new ChatService(store, social, config);
await chat.start();
const app = express();
app.use(createSocialRouter(social, store));
const server = app.listen(0, '127.0.0.1');
await new Promise<void>(resolve => server.once('listening', resolve));
const origin = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
try {
  const a = await social.register('alpha', 'hunter2', 'Alpha');
  const b = await social.register('bravo', 'hunter2', 'Bravo');
  const c = await social.register('charlie', 'hunter2', 'Charlie');
  const alpha = social.findByUsername('alpha')!;
  const bravo = social.findByUsername('bravo')!;
  const charlie = social.findByUsername('charlie')!;
  await social.requestFriend(alpha, 'bravo'); await social.acceptFriend(bravo, 'alpha');
  const challenge = await chat.challenge(alpha);
  await assert.rejects(() => chat.confirm(alpha, 42));
  await chat.propose(42, challenge.code, 'GameAlpha');
  await assert.rejects(() => chat.propose(43, challenge.code, 'Spoof'));
  await assert.rejects(() => chat.confirm(bravo, 42));
  await chat.confirm(alpha, 42);
  await assert.rejects(() => chat.confirm(alpha, 42));
  assert.equal(chat.gameAccount(42).id, alpha.id);
  assert.throws(() => chat.gameAccount(43));
  const expired = await chat.challenge(bravo);
  chat.state.challenges.find(c => c.accountId === bravo.id)!.expiresAt = Date.now() - 1;
  await assert.rejects(() => chat.propose(43, expired.code, 'Expired'));
  const ticket = await chat.helperTicket(42);
  assert.equal(chat.helperAccount(ticket.token).id, alpha.id);
  await social.logout(a.token);
  assert.equal((await social.profileFor(bravo, 'alpha'))!.presence, 'online', 'game keeps presence after launcher logout');
  const image = await sharp({ create: { width: 2, height: 2, channels: 4, background: '#b88a44' } }).png().toBuffer();
  const upload = await chat.upload(alpha, 'dm:bravo', Readable.from(image), 'image/png');
  const send = await social.sendMessage(alpha, 'bravo', 'picture', [upload.id], 'retry_123456');
  await chat.report(bravo, 'dm:alpha', send.id, 'Fixture report');
  assert.equal(chat.state.reports!.length, 1);
  const duplicate = await social.sendMessage(alpha, 'bravo', 'picture', [upload.id], 'retry_123456');
  assert.equal(send.id, duplicate.id);
  await assert.rejects(() => social.sendMessage(alpha, 'bravo', 'changed', [upload.id], 'retry_123456'));
  await social.messagesWith(bravo, 'alpha', 0);
  assert.equal(send.readAt, null);
  await chat.read(bravo, 'dm:alpha', send.id);
  assert.ok(send.readAt);
  assert.equal(chat.download(bravo, upload.id).id, upload.id);
  assert.throws(() => chat.download(charlie, upload.id));
  const authenticated = await fetch(`${origin}/api/v2/social/chat/attachments/${upload.id}`, { headers: { authorization: `Bearer ${b.token}` } });
  assert.equal(authenticated.status, 200);
  assert.equal(authenticated.headers.get('cache-control'), 'private, no-store');
  const helperIndex = process.argv.indexOf('--helper');
  if (helperIndex >= 0) {
    await social.setAvatar(bravo, image.toString('base64'), 'image/png');
    const pixels = Buffer.from([255, 0, 0, 255, 255, 0, 0, 255, 255, 0, 0, 255, 255, 0, 0, 255,
      0, 0, 255, 255, 0, 0, 255, 255, 0, 0, 255, 255, 0, 0, 255, 255]);
    const gif = await sharp(pixels, { raw: { width: 2, height: 4, channels: 4, pageHeight: 2 } }).gif({ delay: [40, 80], loop: 0 }).toBuffer();
    const animation = await chat.upload(alpha, 'dm:bravo', Readable.from(gif), 'image/gif');
    assert.equal(animation.frames, 2);
    await social.sendMessage(alpha, 'bravo', 'animation', [animation.id], 'gif_fixture_123');
    await helperSelftest(process.argv[helperIndex + 1]!, origin, ticket.token, upload.id,
      () => { chat.state.attachments.find(a => a.id === upload.id)!.expiresAt = Date.now() - 1; }, `avatar_${bravo.id}`, animation.id);
    // Only this test lease was expired; preserve the fixture for the other permission checks.
    chat.state.attachments.find(a => a.id === upload.id)!.expiresAt = Date.now() + 60000;
  }
  assert.equal((await fetch(`${origin}/api/v2/social/chat/attachments/${upload.id}`)).status, 401);
  const unauthorizedBridge = await fetch(`${origin}/api/v2/bridge/chat`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' });
  assert.equal(unauthorizedBridge.status, 401);
  const bridge = await fetch(`${origin}/api/v2/bridge/chat`, { method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${config.bridgeSecret}` },
    body: JSON.stringify({ protocolVersion: 1, serverId: config.serverId, realmId: config.realmId, gameId: 42, op: 'send', conversation: 'dm:bravo', body: 'game to launcher', requestId: 'game_send_123' }) });
  assert.equal(bridge.status, 200);
  assert.equal((await bridge.json() as { message: { from: string } }).message.from, 'alpha');
  const raw = await fetch(`${origin}/api/v2/social/chat/attachments?conversation=dm:alpha`, { method: 'POST', headers: { authorization: `Bearer ${b.token}`, 'content-type': 'image/png' }, body: image });
  assert.equal(raw.status, 201, 'binary streaming upload');
  await assert.rejects(() => chat.upload(alpha, 'dm:bravo', Readable.from(Buffer.from('GIF89a bad')), 'image/gif'));
  const large = await sharp({ create: { width: config.media.MaxDimension + 1, height: 1, channels: 3, background: '#000000' } }).png().toBuffer();
  await assert.rejects(() => chat.upload(alpha, 'dm:bravo', Readable.from(large), 'image/png'));
  const originalMax = config.media.MaxUploadBytes;
  config.media.MaxUploadBytes = image.length - 1;
  await assert.rejects(() => chat.upload(alpha, 'dm:bravo', Readable.from(image), 'image/png'));
  config.media.MaxUploadBytes = originalMax;
  // Security rate gating was exercised above; isolate remaining quota/lifecycle fixtures from its minute window.
  config.media.UploadsPerMinute = 1000;
  const quota = config.media.AccountQuotaBytes;
  config.media.AccountQuotaBytes = 1;
  await assert.rejects(() => chat.upload(alpha, 'dm:bravo', Readable.from(image), 'image/png'), /quota/);
  config.media.AccountQuotaBytes = quota;
  await chat.block(bravo, 'alpha', false);
  await assert.rejects(() => social.sendMessage(alpha, 'bravo', 'blocked'));
  assert.throws(() => chat.download(bravo, upload.id));
  await chat.block(bravo, 'alpha', true);
  const group = await social.createGroup(alpha, 'Raid', ['bravo']);
  const groupUpload = await chat.upload(alpha, `group:${group.id}`, Readable.from(image), 'image/png');
  await social.sendGroupMessage(alpha, group.id, '', [groupUpload.id], 'group_send_123');
  assert.equal(chat.groupUnread(bravo, group.id), 1);
  const used = await chat.upload(bravo, 'dm:alpha', Readable.from(image), 'image/png');
  const secondUpload = await chat.upload(bravo, 'dm:alpha', Readable.from(image), 'image/png');
  const combined = config.media.MaxMessageUploadBytes;
  config.media.MaxMessageUploadBytes = image.length;
  await assert.rejects(() => social.sendMessage(bravo, 'alpha', '', [used.id, secondUpload.id], 'combined_upload_123'), /Combined/);
  config.media.MaxMessageUploadBytes = combined;
  await chat.cancel(bravo, secondUpload.id); assert.throws(() => chat.download(bravo, secondUpload.id), /expired/);
  await chat.read(bravo, `group:${group.id}`, 1); assert.equal(chat.groupUnread(bravo, group.id), 0);
  await social.removeGroupMember(alpha, group.id, 'bravo');
  assert.throws(() => chat.download(bravo, groupUpload.id));
  const attachment = chat.state.attachments.find(a => a.id === upload.id)!;
  attachment.expiresAt = Date.now() - 1;
  assert.throws(() => chat.download(alpha, upload.id), /Attachment expired/);
  assert.equal((await fetch(`${origin}/api/v2/social/chat/attachments/${upload.id}`, { headers: { 'x-chat-helper': ticket.token } })).status, 410);
  await chat.cleanup();
  await assert.rejects(() => fs.access(chat.file(upload.id)));
  assert.equal(chat.attachments([upload.id])[0]!.expired, true);
  const retry = chat.state.attachments.find(a => a.id === used.id)!; retry.expiresAt = Date.now() - 1;
  await fs.rm(chat.file(used.id)); await fs.mkdir(chat.file(used.id));
  await chat.cleanup(); assert.equal(retry.cleanupError, true, 'physical deletion failures observable');
  assert.throws(() => chat.download(bravo, used.id), /expired/, 'cleanup failure never extends availability');
  await fs.rmdir(chat.file(used.id)); await chat.cleanup(); assert.equal(retry.cleanupError, false); assert.ok(retry.deletedAt);
  const orphan = chat.state.attachments.find(a => a.id !== upload.id && !a.associated)!;
  orphan.createdAt -= (config.media.OrphanRetentionMinutes + 1) * 60000;
  await chat.cleanup(); assert.ok(orphan.deletedAt);
  const oldExpiry = chat.state.attachments.find(a => a.id === groupUpload.id)!.expiresAt;
  config.media.RetentionHours *= 2;
  await chat.cleanup(); assert.equal(chat.state.attachments.find(a => a.id === groupUpload.id)!.expiresAt, oldExpiry);
  config.media.RetentionHours = 1;
  chat.state.attachments.find(a => a.id === groupUpload.id)!.createdAt -= 2 * 3600000;
  await chat.cleanup(); assert.ok(chat.state.attachments.find(a => a.id === groupUpload.id)!.deletedAt);
  const link = chat.state.links.find(l => l.accountId === alpha.id)!;
  await chat.unlink(alpha, link.id);
  assert.throws(() => chat.helperAccount(ticket.token)); assert.throws(() => chat.gameAccount(42));
  assert.throws(() => chatConfig({ CHAT_MEDIA_RETENTION_HOURS: '0' }));
  assert.throws(() => chatConfig({ CHAT_MEDIA_MAX_UPLOAD_BYTES: '9999999999' }));
  // Concurrent sends must retain every ID, even when save promises interleave.
  chat.rate = () => {};
  const messages = await Promise.all(Array.from({ length: 20 }, (_, i) => social.sendMessage(alpha, 'bravo', String(i), [], `parallel_${i}`)));
  assert.equal(new Set(messages.map(m => m.id)).size, 20);
  const unicode = await Promise.all(Array.from({ length: 12 }, (_, i) => social.sendMessage(alpha, 'bravo', '界'.repeat(1000), [], `unicode_${i}`)));
  let cursor = unicode[0]!.id - 1;
  const received = new Set<number>();
  while (received.size < unicode.length) {
    const page = await chatOperation(chat, bravo, { op: 'history', conversation: 'dm:alpha', since: cursor }) as { messages: Array<{id: number}> };
    assert.ok(Buffer.byteLength(JSON.stringify(page)) <= 23040, 'Unicode history fits the addon transport');
    assert.ok(page.messages.length > 0);
    for (const m of page.messages) received.add(m.id);
    cursor = page.messages.at(-1)!.id;
  }
  assert.equal(received.size, 12, 'bounded pagination does not skip Unicode messages');
  await store.exportLegacy();
  const second = new Store(directory); await second.load();
  await store.saveSocial();
  await assert.rejects(() => second.saveSocial(), /Concurrent/); second.close();
  chat.stop(); store.close();
  store = new Store(directory); await store.load(); social = new SocialService(store); chat = social.chat = new ChatService(store, social, config);
  assert.equal(store.socialData.messages.filter(m => m.requestId?.startsWith('parallel_')).length, 20);
  assert.equal(chat.state.audit.filter(a => a.action === 'unlink').length, 1);
  const exportDir = path.join(directory, 'rollback'); await fs.mkdir(exportDir);
  await fs.copyFile(store.accountsPath, path.join(exportDir, 'accounts.json')); await fs.copyFile(store.socialPath, path.join(exportDir, 'social.json'));
  const migrated = new Store(exportDir); await migrated.load(); assert.equal(migrated.socialData.messages.length, store.socialData.messages.length); migrated.close();
  const corruptDir = path.join(directory, 'corrupt'); await fs.mkdir(corruptDir); await fs.writeFile(path.join(corruptDir, 'accounts.json'), '{broken');
  const corrupt = new Store(corruptDir); await assert.rejects(() => corrupt.load()); corrupt.close();
  assert.equal(await fs.readFile(path.join(corruptDir, 'accounts.json'), 'utf8'), '{broken', 'corrupt source is preserved');
  console.log('chat selftest passed: linking, scoped auth, streaming, quotas, read state, retries, presence, permissions, expiry, cleanup, restart and rollback');
} finally {
  chat.stop(); store.close();
  await new Promise<void>(resolve => server.close(() => resolve()));
  await fs.rm(directory, { recursive: true, force: true });
}
