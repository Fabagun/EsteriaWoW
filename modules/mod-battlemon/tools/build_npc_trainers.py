"""Generate spawn-free NPC templates and the battle roster header from npc-trainers.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[1]
UPDATE = REPO / 'data/sql/updates/pending_db_world/rev_1790969531700983800.sql'


def generate():
    rows = json.loads((ROOT / 'data/npc-trainers.json').read_text(encoding='utf-8'))['trainers']
    header = ['// Generated by tools/build_npc_trainers.py; edit data/npc-trainers.json.', '#pragma once',
              '#include "Define.h"', '#include <vector>', '', 'namespace BattlemonNpcTrainers', '{',
              '    struct Definition', '    {', '        uint32 entry;', '        bool random;',
              '        uint8 minimum;', '        uint8 maximum;', '        std::vector<uint32> species;',
              '    };', '', '    inline Definition const* Find(uint32 entry)', '    {',
              '        static std::vector<Definition> const trainers =', '        {']
    for row in rows:
        if row['species']:
            species = ', '.join(map(str, row['species']))
            minimum = row['min_size'] or len(row['species'])
            maximum = row['max_size'] or len(row['species'])
            header.append(f'            {{{row["entry"]}, {str(row["random"]).lower()}, {minimum}, {maximum},')
            header.append(f'                {{{species}}}}},')
    header += ['        };', '        for (Definition const& trainer : trainers)',
               '            if (trainer.entry == entry)', '                return &trainer;',
               '        return nullptr;', '    }', '}', '']
    (ROOT / 'src/BattlemonNpcTrainers.h').write_text('\n'.join(header), encoding='utf-8', newline='\n')
    ids = ',\n        '.join(', '.join(str(row['entry']) for row in rows[i:i+8]) for i in range(0,len(rows),8))
    script = {'teacher': 'pokemon_trainer_teacher', 'healer': 'pokemon_trainer_nurse', 'guard': ''}
    titles = {'teacher': 'Pokemon Trainer Profession', 'healer': 'Pokemon Healing and Supplies',
              'guard': 'Pokemon Center Security', 'trainer': 'Pokemon Trainer and Supplies',
              'leader': 'Gym Leader', 'elite': 'Elite Four'}
    values = []
    for row in rows:
        role = row['role']
        name = row['name'].replace("'", "''")
        values.append(f"        ({row['entry']}, '{name}', '{titles[role]}', 30, 30, 35, "
                      f"{0 if role == 'guard' else 1}, 1, 7, 2000, 2000, 1,\n"
                      f"            '{script.get(role, 'npc_battlemon_trainer')}')")
    owned = []
    for row in rows:
        name = row['name'].replace("'", "''")
        owned.append(f"(`entry` = {row['entry']} AND `name` = '{name}'\n                "
                     f"AND `ScriptName` = '{script.get(row['role'], 'npc_battlemon_trainer')}')")
    ownership = '\n            OR '.join(owned)
    sql = f'''-- Pokemon NPC templates only. No creature spawns are added, moved, or replaced.
-- Install gym-trainer server DBC continuations before starting worldserver.
DROP PROCEDURE IF EXISTS `install_battlemon_npc_trainers`;
DELIMITER //
CREATE PROCEDURE `install_battlemon_npc_trainers`()
BEGIN
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;
    IF EXISTS (SELECT 1 FROM `creature_template` WHERE `entry` IN ({ids})
        AND NOT ({ownership})) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Pokemon NPC entry collision; no data changed';
    END IF;
    START TRANSACTION;
    DELETE FROM `creature_template_model` WHERE `CreatureID` IN ({ids});
    DELETE FROM `creature_template` WHERE `entry` IN ({ids});
    INSERT INTO `creature_template`
        (`entry`, `name`, `subname`, `minlevel`, `maxlevel`, `faction`, `npcflag`, `unit_class`, `type`,
        `BaseAttackTime`, `RangeAttackTime`, `RegenHealth`, `ScriptName`)
    VALUES
''' + ',\n'.join(values) + ';\n'
    sql += '    INSERT INTO `creature_template_model` (`CreatureID`, `Idx`, `CreatureDisplayID`, `DisplayScale`, `Probability`)\n    VALUES\n'
    sql += ',\n'.join(f"        ({row['entry']}, 0, {row['display']}, 1, 1)" for row in rows) + ';\n'
    # Existing valid model metadata may be used by manually morphed creatures; preserve it.
    females = {950101, 950102, 950103, 950104, 950107, 950111, 950113, 950114, 950116, 950118, 950120, 950121}
    sql += f"    DELETE FROM `creature_model_info` WHERE `DisplayID` IN ({ids})\n"
    sql += "        AND `BoundingRadius` = 0 AND `CombatReach` = 0;\n"
    sql += "    INSERT INTO `creature_model_info` (`DisplayID`, `BoundingRadius`, `CombatReach`, `Gender`,\n"
    sql += "        `DisplayID_Other_Gender`)\n"
    sql += "    SELECT `n`.`DisplayID`, 0.306, 1.5, `n`.`Gender`, 0 FROM (\n"
    sql += '\n        UNION ALL '.join(f"        SELECT {r['display']} AS `DisplayID`, "
                                     f"{1 if r['display'] in females else 0} AS `Gender`" for r in rows)
    sql += "\n    ) AS `n` WHERE NOT EXISTS (SELECT 1 FROM `creature_model_info` AS `m`\n"
    sql += "        WHERE `m`.`DisplayID` = `n`.`DisplayID`);\n"
    sql += '    COMMIT;\nEND//\nDELIMITER ;\nCALL `install_battlemon_npc_trainers`();\nDROP PROCEDURE `install_battlemon_npc_trainers`;\n'
    UPDATE.write_text(sql, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    generate()
