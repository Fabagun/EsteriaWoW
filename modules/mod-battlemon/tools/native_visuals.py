"""Validate native visual references against the installed client and server DBCs, then emit C++."""
import argparse, hashlib, json, struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def table(paths):
    rows={}
    for p in paths:
        b=p.read_bytes()
        if b[:4]!=b'WDBC':raise ValueError('Not WDBC: '+str(p))
        n,f,size,ss=struct.unpack_from('<4I',b,4)
        if size!=f*4 or len(b)!=20+n*size+ss:raise ValueError('Malformed DBC: '+str(p))
        strings=b[20+n*size:]
        for i in range(n):
            r=struct.unpack_from('<'+str(f)+'I',b,20+i*size);rows[r[0]]=(r,strings,str(p))
    return rows

def text(row,col):
    r,s,_=row;start=r[col];return s[start:s.index(b'\0',start)].decode('utf-8')

def validate(config,client,server):
    records=[]
    ct={t:table(sorted(client.glob(t+'.dbc*'))) for t in ['Spell','SpellVisual','SpellVisualKit','SpellVisualEffectName']}
    st={t:table([server/'dbc'/(t+'.dbc')]+sorted((server/'dbc-continuations').glob(t+'.dbc*'))) for t in ct}
    for name,id in config['spells'].items():
        a=ct['Spell'][id];b=st['Spell'][id]
        if a[0][131:133]!=b[0][131:133] or a[0][47]!=b[0][47] or text(a,136)!=text(b,136):
            raise ValueError('Client/server spell mismatch: '+name)
        if a[0][5]&0x44:raise ValueError('Channeled visual needs explicit cleanup: '+name)
        v=a[0][131]
        if not v:raise ValueError('No visual: '+name)
        visual=ct['SpellVisual'][v][0]
        if visual!=st['SpellVisual'][v][0]:raise ValueError('Client/server visual mismatch: '+name)
        kits=[visual[c] for c in [1,2,3,4,5,6,14,15,22,23] if visual[c]]
        for kit in kits:
            if ct['SpellVisualKit'][kit][0]!=st['SpellVisualKit'][kit][0]:raise ValueError('Kit mismatch')
        missile=visual[8]
        path=text(ct['SpellVisualEffectName'][missile],1) if missile and missile in ct['SpellVisualEffectName'] else None
        records.append(dict(profile_spell=name,id=id,name=text(a,136),visual=v,kits=kits,missile_asset=path,
            speed=struct.unpack('<f',struct.pack('<I',a[0][47]))[0],client_table=a[2],server_table=b[2]))
    return records

def header(config):
    lines=['// Generated by tools/native_visuals.py from validated local WoW data.','#pragma once','#include <cstdint>','#include <string>','#include <unordered_map>','','namespace BattlemonNativeEffects','{','enum Spell : uint32_t','{']
    lines += ['    '+n+' = '+str(i)+',' for n,i in config['spells'].items()]
    lines += ['};','','struct Profile','{','    uint32_t spell;','    uint32_t windup;','    uint32_t repeats;','    uint32_t interval;','    bool self;','    bool lunge;','};','']
    for name,p in config['profiles'].items():
        values=[p['spell'],str(p['windup']),str(p['repeats']),str(p['interval']),str(p['self']).lower(),str(p['lunge']).lower()]
        lines.append('inline constexpr Profile '+name+'Profile = {'+', '.join(values)+'};')
    for label,mapping in [('Overrides',config['overrides']),('Special',config['special'])]:
        lines += ['', 'inline std::unordered_map<std::string, Profile> const '+label+' =','{']
        lines += ['    {"'+n+'", '+p+'Profile},' for n,p in sorted(mapping.items())]
        lines += ['};']
    lines += ['', 'inline Profile Select(std::string const& move, std::string const& type, std::string const& category)','{',
      '    if (auto it = Overrides.find(move); it != Overrides.end())','        return it->second;',
      '    if (category == "Status")','        return PainProfile;',
      '    if (category == "Physical")','    {',
      '        auto it = Special.find(type);','        Profile result = it != Special.end() ? it->second : StrikeProfile;',
      '        if (type == "NORMAL")','            result = StrikeProfile;',
      '        result.lunge = true;','        result.windup = 360;','        return result;','    }',
      '    auto it = Special.find(type);','    return it != Special.end() ? it->second : ArcaneBlastProfile;','}','}']
    return '\n'.join(lines)+'\n'

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--client-dbcs',type=Path,required=True);ap.add_argument('--server-data',type=Path,required=True);a=ap.parse_args()
    p=ROOT/'data/native-visuals.json';config=json.loads(p.read_text(encoding='utf-8'));records=validate(config,a.client_dbcs,a.server_data)
    for profile in config['profiles'].values():
        assert profile['spell'] in config['spells'] and 1<=profile['repeats']<=3 and 150<=profile['windup']<=600
    assert all(p in config['profiles'] for p in list(config['special'].values())+list(config['overrides'].values()))
    (ROOT/'src/BattlemonNativeEffects.h').write_text(header(config),encoding='utf-8',newline='\n')
    out=ROOT/'generated/native-effects';out.mkdir(parents=True,exist_ok=True)
    (out/'dbc-validation.json').write_text(json.dumps(dict(passed=True,config_sha256=hashlib.sha256(p.read_bytes()).hexdigest(),spells=records,move_overrides=len(config['overrides']),types=len(config['special'])),indent=2),encoding='utf-8')
    print('Validated',len(records),'native spells,',len(config['overrides']),'move overrides and',len(config['special']),'type fallbacks')
if __name__=='__main__':main()
