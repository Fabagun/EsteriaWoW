"""Generate matched client/server Centaur travel spells from existing Wrath spells."""

import struct

import drakkin_drakonid_racials as shared
import retroported_race_pack as p

# id, donor, name, minimum level, speed; the server hook also enforces riding skill.
ABILITIES = ((111000, 458, 'Gallop', 20, 60), (111001, 458, 'Swift Gallop', 40, 100),
             (111002, 33943, 'Spirit of the Wind', 60, 60),
             (111003, 40120, 'Swift Spirit of the Wind', 70, 280))
TEXT_FIELDS = {field for start in (136, 153, 170, 187) for field in range(start, start + 16)}


def generate(data):
    table = p.RawWdbc(data)
    columns, index = shared.spell_columns(), shared.field_index()
    rows = {p._value(row, 0): row for row in table.records}
    pool, additions, statements = bytearray(table.strings), [], []
    for identifier, donor, name, level, speed in ABILITIES:
        if identifier in rows:
            raise ValueError('Centaur spell ID already present: ' + str(identifier))
        row = list(struct.unpack('<234I', rows[donor]))
        values = {'ID': identifier, 'BaseLevel': level, 'SpellLevel': level,
                  'ManaCost': 0, 'ManaCostPerLevel': 0, 'ManaCostPct': 0,
                  'SpellClassSet': 0, 'SpellClassMask_1': 0, 'SpellClassMask_2': 0,
                  'SpellClassMask_3': 0, 'ModalNextSpell': 0}
        if donor == 458:
            # Keep Wrath mount admission/cancellation semantics, but never create a riding model.
            values.update(EffectMiscValue_1=0, EffectBasePoints_2=speed - 1, CastingTimeIndex=16,
                          SpellVisualID_1=0, SpellVisualID_2=0)
        for field, value in values.items():
            row[index[field]] = shared._pack(value, columns[index[field]][1])
        for field in TEXT_FIELDS:
            row[field] = 0
        description = (f'Run on your own hooves at {speed}% increased speed. Requires riding training.'
                       if donor == 458 else
                       f'Take the form of a bird and fly at {speed}% increased speed. Requires riding training '
                       'and a location where flight is permitted.')
        for field, value in ((136, name), (153, 'Centaur Racial'), (170, description),
                             (187, f'Movement speed increased by {speed}%.')):
            row[field] = len(pool)
            pool.extend(value.encode() + b'\0')
        additions.append(struct.pack('<234I', *row))
        names, values = [], []
        for position, (column, kind) in enumerate(columns):
            if not row[position]:
                continue
            if kind == 'string':
                value = shared._quote(p._string(bytes(pool), row[position]).decode())
            else:
                value = shared._sql_value(row[position], kind)
            names.append('`' + column + '`')
            values.append(value)
        statements.append(f'DELETE FROM `spell_dbc` WHERE `ID` = {identifier};\n'
                          + 'INSERT INTO `spell_dbc` (' + ', '.join(names) + ') VALUES\n('
                          + ', '.join(values) + ');')
    output = table.build([*table.records, *additions], bytes(pool))
    sql = ('-- Generated by tools/centaur_racials.py; client Spell.dbc and server rows must ship together.\n'
           + '\n'.join(statements) + '\n')
    check(output)
    return output, sql


def check(data):
    table = p.RawWdbc(data)
    index = shared.field_index()
    rows = {p._value(row, 0): row for row in table.records}
    for identifier, donor, _, level, speed in ABILITIES:
        row = rows[identifier]
        value = lambda name: p._value(row, index[name] * 4)
        assert value('SpellLevel') == level and value('SpellClassSet') == 0
        assert not value('ManaCost') and not value('ManaCostPct')
        if donor == 458:
            assert value('EffectAura_1') == 78 and value('EffectMiscValue_1') == 0
            assert value('EffectAura_2') == 32 and value('EffectBasePoints_2') == speed - 1
        else:
            assert value('EffectAura_1') == 36 and value('EffectAura_3') == 201
            assert value('AttributesEx4') & 0x20000000  # ONLY_FLYING_AREAS retains zone/cold-weather checks.
            assert not value('AttributesEx7') & 0x00400000
