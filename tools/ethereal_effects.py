"""Generate the Dreadnaught's exact Retail particle palettes from the pinned source audit."""

import json
import hashlib

import ethereal_source as source

PALETTES = ((2423, 'Shadowguard'), (1101, 'Violet'), (2358, 'Amber'), (2421, 'Teal'),
            (2424, 'Lavender'), (2481, 'Shifting'), (2557, 'Crimson'))


def main():
    report = json.loads((source.WORK / 'particle-colors.json').read_text())
    assert report['build'] == source.BUILD
    assert hashlib.sha256((source.WORK / 'source/ParticleColor.db2').read_bytes()).hexdigest() == report['decoded_sha256']
    assert set(map(int, report['rows'])) == {identifier for identifier, _ in PALETTES}
    lines = ['// Generated by EsteriaWoW/tools/ethereal_effects.py from Retail ParticleColor.',
             '// Source content build: ' + source.BUILD,
             '#ifndef ENGINE_SOURCE_RETAIL_ETHEREALEFFECTS_H', '#define ENGINE_SOURCE_RETAIL_ETHEREALEFFECTS_H',
             '#include <array>', '#include <cstdint>', '', 'namespace Retail::Ethereal {',
             'struct EffectPalette {', '    uint32_t id;', '    const char* name;',
             '    std::array<uint32_t, 3> start, mid, end;', '};', 'inline constexpr EffectPalette Effects[] = {']
    for identifier, name in PALETTES:
        row = report['rows'][str(identifier)]
        assert row['ID'] == identifier and all(len(row[field]) == 3 for field in ('Start', 'MID', 'End'))
        colors = ['{' + ','.join(f'0x{value & 0xffffffff:08x}u' for value in row[field]) + '}'
                  for field in ('Start', 'MID', 'End')]
        lines.extend([f'    {{{identifier}, "{name}", {colors[0]},',
                      '        ' + colors[1] + ', ' + colors[2] + '},'])
    lines.extend(['};', '}', '#endif', ''])
    path = source.NATIVE / 'Engine/Source/Retail/EtherealEffects.h'
    path.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('Generated seven source-authored Dreadnaught effect palettes:', path)


if __name__ == '__main__':
    main()
